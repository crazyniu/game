#!/usr/bin/env python3
"""make_skin_table.py: write docs/work-log/world-birds/skins.md, the three skins of every world bird.

The designs are the 45 of docs/work-log/skin-redesign/spec.md. A bird of a species slot in world w (2..10) wears three of the designs of that slot, taken in a cycle
so that the three of a bird differ and every design is used across the worlds: tier t of world w is design ((w-2)*3 + t-1) mod n of the slot's designs. The owl's
propeller beanie (cocoa 4) moves with a painted propeller and is left out. The table has the format refs.py reads (species = bird id, slot = tier 1-3).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
slots = ["sunny", "sky", "berry", "mint", "cocoa", "snow", "ember", "ink", "hoot"]
designs = {}
for line in open(ROOT + "/docs/work-log/skin-redesign/spec.md"):
    c = [x.strip() for x in line.strip().strip("|").split("|")]
    if len(c) == 6 and c[1].isdigit() and c[0] in slots:
        designs.setdefault(c[0], {})[int(c[1])] = c
birds = {}
for line in open(HERE + "/birds.tsv"):
    w, bird, _ = line.rstrip("\n").split("\t")[:3]
    birds.setdefault(int(w), []).append(bird)
rows = []
for w in range(2, 11):
    for slot, bird in zip(slots, birds[w]):
        pool = [n for n in sorted(designs[slot]) if not (slot == "cocoa" and n == 4)]
        for t in (1, 2, 3):
            d = designs[slot][pool[((w - 2) * 3 + t - 1) % len(pool)]]
            rows.append("| %s | %d | %s | %s | %s | %s |" % (bird, t, d[2], d[3], d[4], d[5]))
out = ["# Skins of the world birds", "",
       "Generated by `tools/birds/world_designs/make_skin_table.py` (do not edit by hand): three skins per world bird, the designs of "
       "`docs/work-log/skin-redesign/spec.md` in a cycle per slot. Tiers 1-3 take the prices of outfit tiers 1-3.", "",
       "| Bird | Tier | Name | Class | Costume | Palette |", "|---|---|---|---|---|---|"] + rows
open(ROOT + "/docs/work-log/world-birds/skins.md", "w").write("\n".join(out) + "\n")
print(len(rows), "skins")
